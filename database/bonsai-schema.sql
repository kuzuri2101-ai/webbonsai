-- Admin/editor policy helper. The role is stored in bv_profiles and checked against auth.uid().
create or replace function public.bv_is_editor()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.bv_profiles
    where id = auth.uid() and role in ('ADMIN','EDITOR')
  );
$$;

