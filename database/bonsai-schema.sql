create table if not exists public.bv_works (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  artist_id bigint references public.bv_artists(id) on delete set null,
  plant_id bigint not null references public.bv_plants(id) on delete restrict,
  form_id bigint references public.bv_forms(id) on delete set null,
  style_id bigint references public.bv_styles(id) on delete set null,
