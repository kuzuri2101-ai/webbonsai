-- BONSAI VIET - content database for Supabase/PostgreSQL
-- Run after the existing auth setup. This schema uses auth.users for accounts.

create extension if not exists pgcrypto;

create table if not exists public.bv_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Người yêu cây',
  avatar_url text,
  role text not null default 'USER' check (role in ('USER','AUTHOR','ARTIST','MODERATOR','EDITOR','ADMIN')),
  bio text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bv_locations (
  id bigint generated by default as identity primary key,
  name text not null,
  address text,
  province text,
  district text,
  latitude numeric(10,7),
  longitude numeric(10,7),
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.bv_plants (
  id bigint generated by default as identity primary key,
  name text not null,
  scientific_name text,
  slug text not null unique,
  short_description text,
  description text,
  origin text,
  growth_rate text,
  difficulty text check (difficulty in ('BEGINNER','INTERMEDIATE','ADVANCED')),
  sunlight text,
  watering text,
  soil text,
  root_characteristics text,
  trunk_characteristics text,
  pruning_notes text,
  wiring_notes text,
  propagation_notes text,
  featured_image text,
  status text not null default 'DRAFT' check (status in ('DRAFT','PUBLISHED','ARCHIVED','HIDDEN')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bv_techniques (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  category text,
  difficulty text check (difficulty in ('BEGINNER','INTERMEDIATE','ADVANCED')),
  description text,
  tools_required text,
  best_season text,
  safety_notes text,
  common_mistakes text,
  expert_tips text,
  status text not null default 'DRAFT' check (status in ('DRAFT','PUBLISHED','ARCHIVED','HIDDEN')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bv_forms (
  id bigint generated by default as identity primary key,
